#pragma once
/*
 * kuz_ctr.h — режим гаммирования со счётчиком (CTR) для «Кузнечика»
 *             плюс преобразования hex <-> байты <-> BigInt.
 *
 * Зачем это нужно. grasshopperCode() шифрует ровно один блок в 128 бит
 * (16 байт). Сообщение пользователя имеет произвольную длину, поэтому нужен
 * «режим работы» — правило, как применить 16-байтовую функцию к N байтам.
 * Здесь реализован CTR (ГОСТ Р 34.13-2015 называет его гаммированием):
 *
 *     блок счётчика_i = IV (8 байт) || i (8 байт, big-endian)
 *     гамма_i         = grasshopperCode(блок счётчика_i, ключ)
 *     шифртекст_i     = открытый текст_i XOR гамма_i
 *
 * Почему именно CTR:
 *   1. Не нужно выравнивание (padding) — последний блок гаммы просто
 *      обрезается по длине остатка, шифртекст равен по длине открытому тексту.
 *   2. Шифрование и расшифрование — одна и та же операция, потому что
 *      XOR обратен сам себе: (p ^ g) ^ g = p.
 *   3. grasshopperDeCode() вообще не нужен.
 *
 * Правило, которое нельзя нарушать: пара (ключ, IV) не используется дважды.
 * При повторе гамма та же, и XOR двух шифртекстов даёт XOR двух открытых
 * текстов — ключ сокращается, оба сообщения восстановимы.
 */

#include <cstdint>
#include <string>
#include <vector>
#include "BigInt.h"

const size_t KUZ_BLOCK_BYTES = 16;   // размер блока «Кузнечика», 128 бит
const size_t KUZ_KEY_BYTES   = 32;   // размер ключа, 256 бит
const size_t KUZ_IV_BYTES    = 8;    // половина блока счётчика; вторая — номер блока

/** Байты -> строчный hex. Один байт — ровно две hex-цифры. */
std::string bytesToHex(const std::vector<uint8_t>& bytes);

/** Hex -> байты. Бросает std::invalid_argument на нечётную длину или мусор. */
std::vector<uint8_t> hexToBytes(const std::string& hex);

/** Блок байтов (big-endian) -> BigInt. */
BigInt bytesToBigInt(const std::vector<uint8_t>& bytes);

/**
 * BigInt -> ровно `width` байт, big-endian, с ведущими нулями.
 *
 * Фиксированная ширина здесь принципиальна: BigInt::str() отбрасывает ведущие
 * нули, и блок гаммы, начинающийся с нулевого байта, молча стал бы короче —
 * XOR сдвинулся бы, и один блок из 256 портился бы без всяких сообщений.
 * Все обратные преобразования идут только через эту функцию.
 */
std::vector<uint8_t> bigIntToBytes(const BigInt& value, size_t width);

/**
 * Зашифровать (= расшифровать) данные на месте в режиме CTR.
 *
 * @param data изменяется на месте; длина сохраняется
 * @param key  256-битный ключ
 * @param iv   8 байт, уникальные для каждого сообщения
 */
void kuznyechikCtr(std::vector<uint8_t>& data, const BigInt& key,
                   const std::vector<uint8_t>& iv);
